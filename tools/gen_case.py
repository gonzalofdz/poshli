#!/usr/bin/env python3
#
#  POSHLI - Unicode case mapping data generator (development tool only)
#
#  GNU Lesser General Public License v3.0
#
#  Generates src/case_data.sh, the case mapping data consumed at runtime
#  by lower/upper in src/str.sh. Writes to standard output:
#
#	make case-data
#	(plainly: python3 tools/gen_case.py > src/case_data.sh)
#
#  Source of truth: the Unicode Character Database embedded in CPython's
#  unicodedata module. The mapping rule is Unicode case mapping without
#  contextual or language-specific rules: the simple mappings plus the
#  unconditional one-to-many mappings of SpecialCasing, which is exactly
#  what chr(c).lower() and chr(c).upper() implement.
#
#  Reproducibility: the data is pinned to Unicode 15.0.0
#  (EXPECTED_UNICODE_VERSION below). If the Python interpreter embeds a
#  different unicodedata version, the generator refuses to run instead
#  of silently regenerating src/case_data.sh with new data. Following a
#  new Unicode version is a deliberate act: update the pin (and the
#  documented version) and regenerate.
#
#  Python is a development-only tool: the generated data is plain ASCII
#  and the runtime needs nothing beyond POSIX shell and POSIX utilities.
#
#  Output format (per line; code points in uppercase hex, delta in signed
#  decimal). A code point with no record is preserved unchanged:
#
#	D <lo> <hi> <delta>    every code point in [lo,hi] maps to cp+delta
#	E <src> <dst>          code point src maps to dst
#	X <src> <dst>...       code point src maps to the code points dst...
#

import sys
import unicodedata

EXPECTED_UNICODE_VERSION = "15.0.0"

TEMPLATE = """# shellcheck shell=sh
#
#  POSHLI - Generated Unicode case mapping data
#
#  GNU Lesser General Public License v3.0
#
#  DO NOT EDIT. Generated by tools/gen_case.py ("make case-data").
#
#  Source: the Unicode Character Database embedded in CPython
#  unicodedata (Unicode %s). Mapping rule: Unicode simple case mapping
#  plus the unconditional one-to-many mappings; contextual and
#  language-specific rules are intentionally not implemented.
#
#  Record format (ASCII only; code points in uppercase hex, delta in
#  signed decimal). A code point with no record is preserved unchanged.
#
#\tD <lo> <hi> <delta>\tevery code point in [lo,hi] maps to cp+delta
#\tE <src> <dst>\t\tcode point src maps to dst
#\tX <src> <dst>...\tcode point src maps to the code points dst...
#

if [ -z "${_POSHLI_CASE_LOADED+x}" ]; then
_POSHLI_CASE_LOADED=1

_POSHLI_CASE_LOWER='%s'
_POSHLI_CASE_UPPER='%s'
fi
"""


def build_mapping(direction):
	"""Return cp -> tuple of target code points where the mapping changes."""
	mapping = {}
	for cp in range(0x110000):
		if 0xD800 <= cp <= 0xDFFF:  # surrogates are not UTF-8 scalar values
			continue
		ch = chr(cp)
		converted = ch.lower() if direction == "lower" else ch.upper()
		if converted != ch:
			mapping[cp] = tuple(ord(x) for x in converted)
	return mapping


def compress(one_to_one):
	"""Compress sorted (cp, dst) pairs into constant-delta range records.

	A run of two or more consecutive code points sharing the same delta
	becomes one "D" record; a singleton becomes one "E" record.
	"""
	runs = []
	for cp, dst in one_to_one:
		delta = dst - cp
		if runs and cp == runs[-1][1] + 1 and delta == runs[-1][2]:
			runs[-1][1] = cp
		else:
			runs.append([cp, cp, delta])
	d_records = []
	e_records = []
	for lo, hi, delta in runs:
		if lo == hi:
			e_records.append("E %04X %04X" % (lo, lo + delta))
		else:
			d_records.append("D %04X %04X %d" % (lo, hi, delta))
	return d_records, e_records


def records(direction):
	"""Return the record lines for one direction (lower or upper)."""
	mapping = build_mapping(direction)
	one_to_one = []
	x_records = []
	for cp in sorted(mapping):
		targets = mapping[cp]
		if len(targets) == 1:
			one_to_one.append((cp, targets[0]))
		else:
			x_records.append(
				"X %04X %s" % (cp, " ".join("%04X" % t for t in targets)))
	d_records, e_records = compress(one_to_one)
	return d_records + e_records + x_records


def main():
	if unicodedata.unidata_version != EXPECTED_UNICODE_VERSION:
		sys.exit(
			"gen_case.py: error: data pinned to Unicode %s but this Python "
			"provides Unicode %s.\n"
			"Refusing to generate: src/case_data.sh would change silently. "
			"Use a Python with Unicode %s, or update EXPECTED_UNICODE_VERSION "
			"(and the documented version) on purpose."
			% (EXPECTED_UNICODE_VERSION, unicodedata.unidata_version,
			   EXPECTED_UNICODE_VERSION))
	lower = records("lower")
	upper = records("upper")
	sys.stdout.write(TEMPLATE % (
		unicodedata.unidata_version, "\n".join(lower), "\n".join(upper)))
	print("lower: %d records, upper: %d records (Unicode %s)"
	      % (len(lower), len(upper), unicodedata.unidata_version),
	      file=sys.stderr)


if __name__ == "__main__":
	main()
